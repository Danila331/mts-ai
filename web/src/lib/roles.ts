export const PRIMARY_ROLES = ROLE_IDS.filter((id) => ROLES[id].primary);
export const SEGMENT_ROLES = ROLE_IDS.filter((id) => !ROLES[id].primary);

export function isRole(value: unknown): value is RoleId {
  return typeof value === "string" && (ROLE_IDS as readonly string[]).includes(value);
}

/** Метка над полем ввода: догадка — «Похоже, вы — …», выбор клиента — «Вы — …». */
export function roleLabel(role: RoleId, source: RoleSource | undefined): string {
  return `${source === "client" ? "Вы" : "Похоже, вы"} — ${ROLES[role].who}`;
}

