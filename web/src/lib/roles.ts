type Rule = { words: RegExp[]; self: boolean };

const compile = (pattern: string, self: boolean): Rule => ({
  words: pattern.split(/\s+/).map((w) => new RegExp(`^(?:${w})$`)),
  self,
});

const RULES: { role: RoleId; rules: Rule[] }[] = SPECS.map((s) => ({
  role: s.role,
  rules: [...(s.plain ?? []).map((p) => compile(p, false)), ...(s.self ?? []).map((p) => compile(p, true))],
}));

const SELF_WORDS = new Set(["мы", "я", "являемся", "являюсь", "представляю", "работаю", "работаем"]);
const SELF_WINDOW = 4;

/** Текст как слова: нижний регистр, «ё» → «е», без знаков. */
export function roleWords(text: string): string[] {
  return text
    .toLowerCase()
    .replaceAll("ё", "е")
    .replace(/[^a-z0-9а-я]+/g, " ")
    .split(" ")
    .filter(Boolean);
}

function matchAt(rule: Rule, words: string[], i: number): boolean {
  if (i + rule.words.length > words.length) return false;
  return rule.words.every((w, j) => w.test(words[i + j]));
}

function hasSelf(words: string[], i: number): boolean {
  for (let j = Math.max(0, i - SELF_WINDOW); j < i; j++) if (SELF_WORDS.has(words[j])) return true;
  return false;
}

function detect(text: string, aboutSelf: boolean): RoleId | undefined {
  const words = roleWords(text);
  for (const { role, rules } of RULES) {
    for (const rule of rules) {
      for (let i = 0; i < words.length; i++) {
        if (matchAt(rule, words, i) && (!rule.self || aboutSelf || hasSelf(words, i))) return role;
      }
    }
  }
  return undefined;
}

/** Роль по репликам клиента: первая реплика, где клиент сказал о себе, решает. */
export function detectRole(clientTurns: string[]): RoleId | undefined {
  for (const t of clientTurns) {
    const role = detect(t, false);
    if (role) return role;
  }
  return undefined;
}

/** Роль по полю «Тип организации» паспорта задачи (T2). */
export function roleFromOrgType(orgType: string | undefined): RoleId | undefined {
  return orgType ? detect(orgType, true) : undefined;
}

export interface RoleState {
  role?: RoleId | "";
  roleSource?: RoleSource;
}

/**
 * Роль сессии после новой реплики или паспорта. Выбор клиента (в том числе «не указывать») не трогаем; уже
 * найденная догадка тоже держится — метка не прыгает от реплики к реплике. Иначе — по репликам, затем по типу
 * организации из паспорта.
 */
/**
 * Только поля роли. resolveRole при уже известной роли возвращает переданное состояние целиком (например, всю
 * сессию), и развёрнутое поверх свежего паспорта оно затирало бы его старым.
 */
export function roleFields(r: RoleState): RoleState {
  return { role: r.role, roleSource: r.roleSource };
}

export function resolveRole(state: RoleState, clientTurns: string[], orgType?: string): RoleState {
  if (state.roleSource === "client" || state.role) return state;
  const role = detectRole(clientTurns) ?? roleFromOrgType(orgType);
  return role ? { role, roleSource: "auto" } : state;
}
