export type TopicName = keyof typeof TOPICS;

/** Тема по имени из data-topics; неизвестное имя — undefined (общее приветствие). */
export function topicByName(name: string | null | undefined): Topic | undefined {
  return name && Object.hasOwn(TOPICS, name) ? TOPICS[name as TopicName] : undefined;
}
