def parse_check(text: str) -> str:
    """Чего нет в базе по мнению проверки; пустая строка — ответ в базе есть или вердикт неразборчив."""
    line = " ".join(text.split())
    if "ВЕРДИКТ:" in line:  # формат с цитатой ближайшего места базы
        line = line.rsplit("ВЕРДИКТ:", 1)[1].strip()
    if not line.upper().startswith("НЕТ"):
        return ""
    return line[3:].lstrip(" :—-").rstrip(". ") or "прямого ответа нет"


