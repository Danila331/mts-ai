def static_example_pairs() -> list:
    """Статические примеры EXAMPLES как пары (вопрос, ответ) — для подачи сообщениями."""
    import re as _re
    pairs = []
    for m in _re.finditer(r"Клиент: (.+?)\nКонсультант: (.+?)(?=\n\nКлиент:|\Z)", EXAMPLES, _re.S):
        pairs.append((" ".join(m.group(1).split()), " ".join(m.group(2).split())))
    return pairs


def filter_examples(pairs: list, turns: list) -> list:
    """Исключает пример при совпадении любой реплики с текущим диалогом."""
    def normalized(text):
        return " ".join(text.lower().replace("ё", "е").split())

    current = {normalized(t["content"]) for t in turns if t["content"].strip()}
    return [(q, a) for q, a in pairs
            if not current.intersection(normalized(t["content"]) for t in parse(q))]


def build_draft_messages(materials: str, turns: list) -> list:
    dialog = "\n".join(f"{t['role']}: {t['content']}" for t in turns)
    return [{"role": "system", "content": DRAFT_SYSTEM},
            {"role": "user", "content": f"Фрагменты базы знаний:\n{materials}\n\nДИАЛОГ\n{dialog}"}]


def build_write_messages(materials: str, turns: list, draft: str, mode: str = "eval",
                         use_examples: bool = True, note: str = "", role: str = "", level: str = "") -> list:
    prompt = system_prompt(materials, mode, examples="", role=role, level=level)
    use_examples = use_examples and mode != "copilot"
    if note:
        prompt += "\n\nРЕШЕНИЕ ПО ЭТОМУ ХОДУ\n" + note
    if use_examples:
        examples = filter_examples(static_example_pairs(), turns)
        prompt += "\n\nПРИМЕРЫ СТИЛЯ\n" + "\n\n".join(
            f"Клиент: {q}\nКонсультант: {a}" for q, a in examples
        )
    prompt += "\n\n" + WRITE_TAIL + "\n\nФАКТИЧЕСКАЯ ОСНОВА\n" + draft
    return [{"role": "system", "content": prompt}] + turns


def system_prompt(materials: str, mode: str = "eval", examples: str | None = None, role: str = "",
                  level: str = "") -> str:
    """examples: None — статический текстовый блок (фолбэк); "" — без блока (примеры идут сообщениями).

    Режим eval (автопроверка, solution.py) — байт в байт как без веб-стенда. Только веб-чат: блоки заявки,
    «данные, не инструкции» (T35), роль (T15) и уровень (T16), рамка фрагментов при EB_SPOTLIGHT. Копилот
    менеджера (T11): свои правила формы, без примеров стиля для клиента.
    """
    if mode == "copilot":
        mode_rules, examples = EVAL_MODE + COPILOT_MODE, ""
    else:
        mode_rules = CHAT_MODE if mode == "chat" else EVAL_MODE
    if examples is None:
        block = EXAMPLES
    else:
        block = examples
    sep = f"\n{block}\n" if block else "\n"
    if mode == "chat":
        sep += SPOTLIGHT_NOTE.lstrip("\n") + role_hint(mode, role) + level_hint(mode, level) + "\n"
        materials = spotlight_materials(materials, mode)
    return f"{BASE_RULES}{mode_rules}{sep}\nМАТЕРИАЛЫ\n{materials}"


def render_dialog(turns: list) -> str:
    """Диалог текстом для служебных вызовов стенда (уточняющий вопрос, T12)."""
    if len(turns) == 1:
        return f"ВОПРОС КЛИЕНТА\n{turns[0]['content']}"
    names = {"user": "Клиент", "assistant": "Консультант"}
    lines = [f"{names.get(t['role'], 'Клиент')}: {t['content']}" for t in turns]
    return "ДИАЛОГ (отвечай на последнюю реплику клиента с учётом всего диалога)\n" + "\n".join(lines)


