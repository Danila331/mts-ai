def split_inline_evidence(text: str) -> tuple:
    """(ответ клиенту, опора) из вывода «опора + ответ». Нет метки ОТВЕТ — ответа нет: формат не соблюдён."""
    marker = text.rfind("ОТВЕТ:")
    if marker < 0:
        return ("", "") if "ЦИТАТЫ" in text else (text.strip(), "")
    return text[marker + len("ОТВЕТ:"):].strip(), text[:marker].strip()


def parse_evidence(text: str) -> tuple:
    """(опора для промпта, чего нет в базе). Пустая опора — вызов не дал разборчивого результата."""
    text = text.strip()
    start = text.find("ЦИТАТЫ")
    if start < 0:
        return "", ""
    text = text[start:][:1800]
    missing = ""
    for line in text.splitlines():
        if line.strip().upper().startswith("НЕТ В БАЗЕ"):
            missing = line.split(":", 1)[-1].strip(" .—-–")
    return text, missing


def evidence_note(evidence: str, missing: str) -> str:
    return EVIDENCE_NOTE.format(evidence=evidence, missing=EVIDENCE_MISSING if missing else "")


def _norm(text: str) -> str:
    return " ".join(text.lower().replace("ё", "е").split())


def render_examples(exclude: str = "") -> str:
    """Примеры организаторов. exclude — текст вопроса, который нужно исключить (локальная оценка
    на демо-наборе: иначе модель просто перепишет эталон)."""
    skip = _norm(exclude) if exclude else None
    blocks = []
    for question, answer in EXAMPLES:
        if skip and _norm(question) == skip:
            continue
        if "Ассистент:" in question:
            blocks.append(f"Диалог:\n{question}\nОтвет эксперта: {answer}")
        else:
            blocks.append(f"Клиент: {question}\nОтвет эксперта: {answer}")
    return "\n\n".join(blocks)


_EXAMPLE_TOKENS = [set(tokens(q, expand=True)) for q, _ in EXAMPLES]
_EXAMPLE_DF = Counter(t for ts in _EXAMPLE_TOKENS for t in ts)


def nearest_examples(question: str, k: int = 3, exclude: str = "") -> str:
    """k эталонов организаторов, ближайших к вопросу по словам (редкие слова весят больше).

    Все примеры уже есть в неизменной части промпта, но она далеко от вопроса; самые похожие
    повторяются прямо перед ним — так модель точнее повторяет вывод, отбор фактов и форму эталона."""
    query = set(tokens(question, expand=True))
    skip = _norm(exclude) if exclude else None
    scored = []
    for i, (q, _) in enumerate(EXAMPLES):
        if skip and _norm(q) == skip:
            continue
        common = query & _EXAMPLE_TOKENS[i]
        score = sum(math.log(1 + len(EXAMPLES) / _EXAMPLE_DF[t]) for t in common)
        scored.append((score / math.sqrt(1 + len(_EXAMPLE_TOKENS[i])), i))
    blocks = []
    for score, i in sorted(scored, reverse=True)[:k]:
        if score <= 0:
            break
        q, a = EXAMPLES[i]
        head = f"Диалог:\n{q}" if "Ассистент:" in q else f"Клиент: {q}"
        blocks.append(f"{head}\nОтвет эксперта: {a}")
    return "\n\n".join(reversed(blocks))  # самый похожий — ближе к вопросу


def render_dialog(turns: list) -> str:
    if len(turns) == 1:
        return f"ВОПРОС КЛИЕНТА\n{turns[0]['content']}"
    names = {"user": "Клиент", "assistant": "Консультант"}
    lines = [f"{names.get(t['role'], 'Клиент')}: {t['content']}" for t in turns]
    return "ДИАЛОГ (отвечай на последнюю реплику клиента с учётом всего диалога)\n" + "\n".join(lines)


def build_messages(reference: str, materials: str, turns: list, mode: str = "eval",
                   examples: bool = True, exclude_example: str = "", full_kb: bool = False,
                   plan: int = 0, style: str = "tight", near: int = 0, note: str = "",
                   brief_think: bool = False, task: str = "", role: str = "") -> list:
    """reference — неизменная часть базы (справочник или вся база при full_kb), materials — найденное по вопросу.
    plan: 0 — сразу ответ, 1 — короткий разбор, 2 — разбор с цитатами; style: tight | full."""
    rules = {"full": RULES_FULL, "recipe": RULES_RECIPE, "jury": RULES_JURY, "jury2": RULES_JURY2}.get(style, RULES)
    system = rules + (CHAT_MODE if mode == "chat" else "") + (COPILOT_MODE if mode == "copilot" else "")
    # Эталоны жюри — короткие ответы клиенту: копилоту они задали бы чужую форму.
    examples, near = (False, 0) if mode == "copilot" else (examples, near)
    if reference:
        title = "БАЗА ЗНАНИЙ (все документы)" if full_kb else "СПРАВОЧНИК (общие сведения по всем продуктам)"
        system += f"\n\n{title}\n{reference}"
    if examples:
        system += "\n\nПРИМЕРЫ ЭТАЛОННЫХ ОТВЕТОВ (образец вывода, отбора фактов и длины; факты бери из базы)\n"
        system += render_examples(exclude_example)
    system += role_hint(mode, role)  # в конце: общий префикс (правила, справочник, примеры) кэшируется как прежде
    title = "РАЗДЕЛЫ БАЗЫ, БЛИЖАЙШИЕ К ВОПРОСУ (подсказка поиска; остальная база выше)" if full_kb \
        else "МАТЕРИАЛЫ ПО ВОПРОСУ"
    tail = PLAN_QUOTES if plan == 2 else PLAN_REMINDER if plan else \
        FINAL_REMINDER_FULL if style == "full" else FINAL_REMINDER_JURY if style in ("jury", "jury2") else FINAL_REMINDER
    if plan == 1 and style == "full":
        tail = tail.replace("2–4 предложения, 30–55 слов, один абзац", "3–5 предложений, 45–80 слов, один абзац")
    similar = nearest_examples(" ".join(t["content"] for t in turns), near, exclude_example) if near else ""
    if similar:
        similar = ("ЭТАЛОННЫЕ ОТВЕТЫ ЭКСПЕРТА НА ПОХОЖИЕ ВОПРОСЫ (держись их вывода, отбора фактов, осторожности "
                   f"формулировок и длины)\n{similar}\n\n")
    if mode == "copilot":
        tail = COPILOT_TAIL
    if task:  # другой заказ на тех же материалах (например, опора из базы): общий префикс сохраняется
        tail = task
    if note:
        tail = f"{note}\n\n{tail}"
    if brief_think:
        tail = f"{tail}\n\n{THINK_BRIEF}"
    user = f"{title}\n{materials}\n\n{similar}{render_dialog(turns)}\n\n{tail}"
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


