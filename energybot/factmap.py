def parse_marks(text: str, n: int) -> dict:
    """«номер: оценка» → {номер: оценка 0…10}."""
    marks = {}
    for m in re.finditer(r"(\d+)\s*[:\-–—]\s*(\d+(?:[.,]\d+)?)", text):
        i, v = int(m.group(1)), float(m.group(2).replace(",", "."))
        if i < n:
            marks[i] = max(0.0, min(10.0, v))
    return marks
