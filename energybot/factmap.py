def build_condense_messages(turns: list) -> list:
    return [{"role": "system", "content": CONDENSE_SYSTEM}, {"role": "user", "content": render_dialog(turns)}]


def clean_condensed(text: str) -> str:
    line = next((x for x in text.strip().splitlines() if x.strip()), "")
    line = re.sub(r"^(?:вопрос|самостоятельный вопрос)\s*:\s*", "", line.strip(), flags=re.I)
    return line.strip(" «»\"'")[:400]


