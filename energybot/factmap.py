MAP_DOCS = ("00-product-map.md", "01-numbers-and-indicators.md")
SCOPE_DOC = "02-product-scope-and-limits.md"
SCOPE_SECTIONS = ("Общие границы", "Когда требуется специалист")


def fact_map_chunks(kb) -> list:
    """Разделы базы, из которых состоит карта фактов (в порядке базы)."""
    out = []
    for c in kb.chunks:
        name = Path(c.doc).name
        if name in MAP_DOCS or (c.doc.startswith("20-products/") and c.is_guard) or \
                (name == SCOPE_DOC and c.path in SCOPE_SECTIONS):
            out.append(c)
    return out


def render_fact_map(chunks: list) -> str:
    blocks, current = [], None
    for c in chunks:
        if c.doc != current:
            current = c.doc
            blocks.append(f"=== {c.title} ({c.doc}) ===")
        blocks.append(f"## {c.path}\n{c.text}" if c.path != c.title else c.text)
    return "\n\n".join(blocks)


# ---------- короткая реплика в диалоге → самостоятельный вопрос для поиска ----------
SHORT_REPLY = re.compile(
    r"^(да|нет|ага|угу|ок|окей|хорошо|давайте|конечно|верно|согласен|согласна|понятно|подходит|не знаю)\b", re.I)


def needs_condense(turns: list) -> bool:
    """Только для диалога, где последняя реплика клиента без контекста ничего не значит."""
    if len(turns) < 2:
        return False
    last = turns[-1]["content"].strip()
    return len(last.split()) <= 4 or bool(SHORT_REPLY.match(last))


