"""Схема «карта фактов + гибридный поиск по разделам + проверка чисел» (EB_ARCH=factmap).

- Карта фактов — неизменная часть промпта, одна на все вопросы: карта продуктов, числовые показатели
  с оговорками, у каждого продукта «Факты, которые можно утверждать», «Чего утверждать нельзя», «Что мы
  не делаем», «Не подходит», общие границы консультации. Собирается из базы при запуске, в ZIP не лежит.
- Поиск по разделам: BM25 + символьные n-граммы + bge-m3, слияние RRF (k=60), 12 кандидатов →
  реранкер → 5 разделов. Разделы карты фактов в выдачу не попадают: они и так в промпте.
- Короткая реплика в диалоге («да», «300 кВт») перед поиском переписывается в самостоятельный вопрос.
- Ответ: прямой ответ → факты из базы с оговорками → ровно один уточняющий вопрос; 40–110 слов. Если
  ответа в базе нет — частичный ответ + чего нет в материалах + специалист. Каждое число ответа обязано
  стоять в карте фактов, найденных разделах или репликах клиента (energybot/guard.py).
"""

from __future__ import annotations

