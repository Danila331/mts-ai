import math  # noqa: E402


def _cos(a, b):
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a)) or 1.0
    nb = math.sqrt(sum(x * x for x in b)) or 1.0
    return dot / na / nb


class GoldenExamples:
    """Выбор 1–2 самых близких эталонов жюри по эмбеддингу вопроса.

    skip_self: в локальном eval вопрос совпадает с эталонным — пропускаем его
    (иначе пример = сам эталон, и замер ничего не значит). На платформе вопросы
    скрытые, самосовпадения быть не может. Порог: далёкий эталон по другой теме
    хуже статических примеров — тогда возвращаем пустую строку (фолбэк в prompts).
    """

    def __init__(self, api, threshold=0.45):
        self.threshold = threshold
        self.vecs = None
        try:
            self.vecs = api.embed([q for q, _ in GOLD])
        except Exception as exc:  # noqa: BLE001 — без эмбеддингов просто не работаем
            import sys
            print(f"[gold] эмбеддинги эталонов недоступны: {exc}", file=sys.stderr)

    def pick_pairs(self, query_vec, skip_self: bool = True, n: int = 2) -> list:
        """Пары (вопрос, ответ) ближайших эталонов — для подачи примерами-сообщениями."""
        if query_vec is None or self.vecs is None:
            return []
        sims = [(_cos(query_vec, v), i) for i, v in enumerate(self.vecs)]
        sims.sort(key=lambda x: -x[0])
        out = []
        for sim, i in sims:
            if skip_self and sim > 0.995:
                continue
            if sim < self.threshold:
                break
            out.append(GOLD[i])
            if len(out) == n:
                break
        return out

    def pick(self, query_vec, skip_self: bool = True, n: int = 2) -> str:
        if query_vec is None or self.vecs is None:
            return ""
        sims = [(_cos(query_vec, v), i) for i, v in enumerate(self.vecs)]
        sims.sort(key=lambda x: -x[0])
        out = []
        for sim, i in sims:
            if skip_self and sim > 0.995:
                continue
            if sim < self.threshold:
                break
            out.append((sim, i))
            if len(out) == n:
                break
        if not out:
            return ""
        parts = ["ПРИМЕРЫ ПОХОЖИХ КОНСУЛЬТАЦИЙ (показывают ФОРМУ ответа; факты — только из МАТЕРИАЛОВ)"]
        for _, i in out:
            q, a = GOLD[i]
            parts.append(f"Клиент: {q}\nКонсультант: {a}")
        return "\n\n".join(parts)
