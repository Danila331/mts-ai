"""Классификатор интента последней реплики → обязательный скелет ответа.

Девять типов из разбора эталонов жюри (demo_output.csv): у каждого типа своя
обязательная открывашка и правило про уточняющий вопрос. Проверяется бесплатно:
eval/question_eval.py + первая строка ответа против открывашки эталона.
"""

from __future__ import annotations

import re

# (тип, триггер на последнюю реплику, открывашка, спрашивать: True/False/None=по слотам)
# Порядок — от частных к общим; первое совпадение побеждает.
INTENT_RULES = [
    # Г. Успокоение/риторика: «вы так и скажете?» → короткое подтверждение, без вопроса.
    ("reassurance", r"так и скажете|правда ли|честно|не навр[её]т|уверен",
     "Да, обязательно.", False),
    # Д. «С чего начать» → процесс по шагам и веткам.
    ("where_start", r"с чего (нам )?нач|как начать|с чего нач",
     "Начать стоит с ", None),
    # Ж. Достаточность данных: «хватит ли данных» → «Да, достаточно: …», без вопроса.
    ("sufficiency", r"хватит|достаточн",
     "Да, ", False),
    # И. Нежелание оставить контакт → «Конечно, телефон пока не нужен.»
    ("contact_reluctant", r"не готов.*телефон|без телефона|не хочу.*контакт|оставлять телефон",
     "Конечно, телефон пока не нужен.", None),
    # В. Процессный «сначала?» → «Да, сначала…», без вопроса (кроме orem — там слоты).
    ("process_first", r"сначала (надо|нужно)|с чего.*провер",
     "Да, ", False),
    # Б. Capability сервиса: «разберёт?», «сможет прочитать?» → «Да.», без вопроса.
    ("capability", r"разбер|сможет|сможете|прочит|читает|считает|справится",
     "Да.", False),
    # К. Субстантивный отказ: «стоит ли рассматривать» — БЕЗ «Да/Нет» в начале.
    ("substantive_no", r"стоит ли|рассматривать|стоит вообще|вообще рассмат",
     "", None),
    # Е. Условная целесообразность: «имеет ли смысл при…» → «Может иметь смысл, но…».
    ("conditional", r"имеет ли смысл|есть ли смысл|имеет смысл|вообще",
     "Может иметь смысл, но ", None),
    # З. Анализ/разбор: «разобраться», «что проверить», «вырос» → план разбора.
    ("analysis", r"разобраться|проверить|из-за чего|почему вырос|что провер",
     "Да, ", None),
    # А. Возможность (общий случай): «можно ли», «ставите ли» → «Да,»/«Нет,».
    ("possibility", r"можно|ставите|так можно|можете|подойд|подходит|предлагаете|предлаг",
     "Да, ", None),
]

OPENING_HINT = {
    "reassurance": "коротко подтверди честность правила, без уточняющего вопроса",
    "where_start": "первый шаг, затем ветки решения по условиям клиента",
    "sufficiency": "подтверди достаточность с минимумом из материалов; вопрос не нужен",
    "contact_reluctant": "контакт не требуй; перечисли, что нужно для оценки",
    "process_first": "что измерить/проверить до действия; вопрос не нужен",
    "capability": "короткое подтверждение и состав возможностей; вопрос не нужен",
    "conditional": "условная формулировка «может иметь смысл, но…»: назови механизм из материалов "
                   "(почему экономия ниже) И альтернативу для сравнения из материалов (другую конфигурацию/решение)",
    "substantive_no": "НЕ начинай с «Да»/«Нет»: начни с существительного отказа или оговорки из материалов",
    "analysis": "начни с плана разбора (что сравниваем/проверяем)",
    "possibility": "прямое «Да, …» или «Нет, …» первым словом, затем факт",
}


def classify_intent(last_user: str) -> tuple:
    """(тип, открывашка, спрашивать) по последней реплике клиента; пусто — общий случай."""
    text = last_user.lower()
    for name, pattern, opening, ask in INTENT_RULES:
        if re.search(pattern, text, re.I):
            return name, opening, ask
    return "", "", None


def intent_note(last_user: str) -> str:
    """Строка для блока «РЕШЕНИЕ ПО ЭТОМУ ХОДУ»."""
    name, opening, ask = classify_intent(last_user)
    if not name:
        return ""
    parts = [f"Тип ответа: {name} — {OPENING_HINT[name]}."]
    if opening:
        parts.append(f"Открывай дословно в духе: «{opening}…».")
    if ask is False:
        parts.append("Уточняющий вопрос в конце НЕ нужен — закончи утверждением.")
    return " ".join(parts)
