# Солнечная станция: если разговор уже о мощности/расширении, эталон спрашивает
# профиль потребления, а не регион (demo-3 против demo-1/2).
SOLAR_POWER_TALK = re.compile(r"кВт|мощност|расшир|поэтапн|нараст", re.I)

# Риторика/подтверждение: эталон в таких случаях не задаёт вопрос (demo-13).
RHETORICAL = re.compile(r"так и скажете|правда|уверен|точно ли|честно|не навр[её]т", re.I)

# Процессные «да/нет» вопросы («сначала надо измерить?», «можно ли так?») эталон
# закрывает без встречного вопроса (demo-11).
PROCESS_YESNO = re.compile(r"(сначала|сначала надо|нужно ли|надо ли).*(измер|провер|сделать)", re.I)

# Чистые вопросы о возможности сервиса («сможет ли по фото», «разберёт ли») эталон
# закрывает без вопроса (demo-8, demo-9) — но только для meter_reading.
CAPABILITY = re.compile(r"сможет|сможете|разбер[её]т|прочитать|прочт[её]т|читает", re.I)


# Продукт по тексту диалога (первая реплика несёт тему): надёжнее, чем топ чанка —
# ретрив цепляется за боковые слова («фото» в demo-15/18 тянул meter_reading вместо askue).
DIALOG_PRODUCT = [
    ("solar", r"солнеч|панел|станц|кровл|фасад"),
    ("orem", r"оптов|опт\b|поставщик|сбыт"),
    ("losses", r"потер|хищен|незаконн|небаланс"),
    ("meter_reading", r"по фото|фотограф|фото показаний"),
    ("askue", r"уч[её]т|платформ|сч[её]тчик|прибор|показан"),
    ("tariff", r"тариф|категори|сч[её]т.*вырос|дорог"),
]


def product_from_dialog(dialog: str) -> str:
    for product, pattern in DIALOG_PRODUCT:
        if re.search(pattern, dialog, re.I):
            return product
    return ""


def product_of(docs: list) -> str:
    """Продукт по самому релевантному документу выдачи (фолбэк, если диалог не помог)."""
    for doc in docs:
        name = doc.split("/")[-1]
        if name in PRODUCT_BY_DOC:
            return PRODUCT_BY_DOC[name]
    return ""


def choose_question(product: str, dialog: str, last_user: str) -> str:
    """Первый незаполненный слот очереди продукта — или пустая строка (не спрашивать)."""
    if not product or product not in QUEUES:
        return ""
    if RHETORICAL.search(last_user):
        return ""
    # Процессные «да/нет» эталон закрывает без вопроса (demo-11), КРОМЕ оптового
    # рынка: там жюри всё равно спрашивает мощность (demo-12).
    if product != "orem" and PROCESS_YESNO.search(last_user):
        return ""
    if product == "meter_reading" and CAPABILITY.search(last_user):
        return ""
    queue = QUEUES[product]
    if product == "solar" and SOLAR_POWER_TALK.search(last_user):
        # Тема — мощность/расширение: сначала профиль потребления, потом регион.
        queue = sorted(queue, key=lambda s: 0 if s[0] == "day_profile" else 1 if s[0] == "region" else 2)
    for slot, question, known_re in queue:
        if not re.search(known_re, dialog, re.I):
            return question
    return ""
