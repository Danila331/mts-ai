"""Очереди «необходимых данных» по продуктам — из knowledge-base/00-reference/03-calculation-and-requests.md.

Вопрос в конце ответа выбирается детерминированно: первый слот из очереди продукта,
которого нет в диалоге. Модель формулирует ответ, код решает, о чём спросить и спрашивать ли.
Основания-слоты сверены с эталонами жюри на демо (см. eval/question_eval.py).
"""

from __future__ import annotations

import re

# Документ → продукт
PRODUCT_BY_DOC = {
    "23-solar.md": "solar",
    "22-askue.md": "askue",
    "21-orem.md": "orem",
    "24-losses.md": "losses",
    "25-meter-reading.md": "meter_reading",
    "14-tariffs.md": "tariff",
    "11-price-categories.md": "tariff",
    "12-power-thresholds.md": "tariff",
}

# Очереди слотов: (слот, формулировка вопроса, регекс «слот уже известен из диалога»).
# Формулировки — по стилю вопросов жюри из demo_output.csv.
