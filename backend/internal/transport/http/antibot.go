package http

import "time"

// Антибот формы заявки без CAPTCHA (T35): скрытое поле-ловушка и минимальное
// время заполнения. Человек поле не видит и форму за долю секунды не
// заполняет; скрипт, который подставляет значения во все поля и отправляет
// форму сразу, делает и то и другое.
//
// Это отсев дешёвых ботов, а не защита от целенаправленной атаки: время
// присылает браузер. От потока заявок дальше защищают предел по адресу
// (leadLimit) и согласие на обработку данных.

// Тексты без давления: человек, у которого форма «ушла слишком быстро»
// (автозаполнение браузера), просто отправляет её ещё раз.
const (
	msgTooFast  = "Форма отправилась слишком быстро. Проверьте данные и нажмите «Отправить» ещё раз"
	msgHoneypot = "Не удалось принять заявку. Обновите страницу и попробуйте ещё раз — или напишите в чат, мы поможем"
)

// checkHuman отвечает текстом отказа или пустой строкой, если заявка
// похожа на заявку человека.
//
// honeypot — значение скрытого поля: у человека оно пустое. elapsedMs —
// сколько форма была на экране до отправки; nil — поле не прислали вовсе,
// и это считается слишком быстрой отправкой (бот не знает о поле). min == 0
// выключает проверку времени.
func checkHuman(honeypot string, elapsedMs *int64, min time.Duration) string {
	if honeypot != "" {
		return msgHoneypot
	}
	if min > 0 && (elapsedMs == nil || time.Duration(*elapsedMs)*time.Millisecond < min) {
		return msgTooFast
	}
	return ""
}
